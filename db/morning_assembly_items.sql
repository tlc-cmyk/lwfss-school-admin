-- morning_assembly_items: multiple announcement items per school day
-- Distinct from morning_assemblies (date-level venue / legacy content).
-- Apply on Supabase project lwfss-school-admin (edausixxdclhonkrdzqg)

CREATE TABLE IF NOT EXISTS public.morning_assembly_items (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assembly_date date NOT NULL,
  content text NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0,
  booked_by text NOT NULL DEFAULT '',
  booked_by_code text NOT NULL DEFAULT '',
  booked_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT morning_assembly_items_content_nonempty CHECK (length(btrim(content)) > 0)
);

COMMENT ON TABLE public.morning_assembly_items IS 'Morning assembly announcement items (multiple per day)';
COMMENT ON COLUMN public.morning_assembly_items.assembly_date IS 'Calendar date of the morning assembly';
COMMENT ON COLUMN public.morning_assembly_items.content IS 'Announcement text';
COMMENT ON COLUMN public.morning_assembly_items.sort_order IS 'Display order within the day (0-based)';
COMMENT ON COLUMN public.morning_assembly_items.booked_by IS 'Creator email';
COMMENT ON COLUMN public.morning_assembly_items.booked_by_code IS 'Creator staff short_name if known';

CREATE INDEX IF NOT EXISTS idx_morning_assembly_items_date_sort
  ON public.morning_assembly_items (assembly_date, sort_order, id);

ALTER TABLE public.morning_assembly_items ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS school_read_morning_assembly_items ON public.morning_assembly_items;
CREATE POLICY school_read_morning_assembly_items ON public.morning_assembly_items
  FOR SELECT TO authenticated
  USING (COALESCE((auth.jwt() ->> 'email'::text), ''::text) ~~* '%@g.lwfss.edu.hk'::text);

DROP POLICY IF EXISTS staff_insert_morning_assembly_items ON public.morning_assembly_items;
CREATE POLICY staff_insert_morning_assembly_items ON public.morning_assembly_items
  FOR INSERT TO authenticated
  WITH CHECK (public.is_staff());

DROP POLICY IF EXISTS staff_update_morning_assembly_items ON public.morning_assembly_items;
CREATE POLICY staff_update_morning_assembly_items ON public.morning_assembly_items
  FOR UPDATE TO authenticated
  USING (public.is_staff())
  WITH CHECK (public.is_staff());

DROP POLICY IF EXISTS staff_delete_morning_assembly_items ON public.morning_assembly_items;
CREATE POLICY staff_delete_morning_assembly_items ON public.morning_assembly_items
  FOR DELETE TO authenticated
  USING (public.is_staff());

REVOKE ALL ON TABLE public.morning_assembly_items FROM anon;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.morning_assembly_items TO authenticated;

-- Migrate legacy single content rows into items (idempotent)
INSERT INTO public.morning_assembly_items (assembly_date, content, sort_order, booked_by, booked_by_code, booked_at)
SELECT m.assembly_date, btrim(m.content), 0, COALESCE(m.booked_by, ''), COALESCE(m.booked_by_code, ''), COALESCE(m.booked_at, now())
FROM public.morning_assemblies m
WHERE length(btrim(m.content)) > 0
  AND NOT EXISTS (
    SELECT 1 FROM public.morning_assembly_items i WHERE i.assembly_date = m.assembly_date
  );

UPDATE public.morning_assemblies
SET content = '', updated_at = now()
WHERE length(btrim(content)) > 0;
